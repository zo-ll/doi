import { expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { chromium, type Browser } from "playwright-core";
import { parseConfig } from "../src/config.ts";
import { startServer } from "../src/server/app.ts";
import { readArchitecture } from "../src/workspace/architecture.ts";
const hasBrowser = await chromium.launch().then(browser => browser.close().then(() => true), () => false);
test.if(!!process.env.CI)("CI has Chromium for UML", () => expect(hasBrowser).toBe(true));

test.skipIf(!hasBrowser)("UML is optional, edits real graphs, preserves data and returns to the linked UI", async () => {
  const workspace = await mkdtemp(join(tmpdir(), "doi-uml-browser-"));
  let browser: Browser | undefined, app: Awaited<ReturnType<typeof startServer>> | undefined;
  try {
    app = await startServer(parseConfig({ workspace }), { port: 0, development: false });
    browser = await chromium.launch();
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: "dark" });
    await context.route("**/api/providers", route => route.fulfill({ json: [] }));
    const page = await context.newPage(); page.setDefaultTimeout(5000);
    const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
    let turns = 0; page.on("request", req => { if (req.method() === "POST" && req.url().endsWith("/turns")) turns++; });
    const initialHtml = await Bun.file(join(workspace, "projects/sample/designs/home/index.html")).text();
    await page.goto(`http://127.0.0.1:${app.server.port}/?project=sample&design=home`, { waitUntil: "domcontentloaded" });
    await page.getByRole("tab", { name: "UML", exact: true }).click();
    await page.getByRole("button", { name: "Add UML to this project", exact: true }).waitFor();
    expect(await Bun.file(join(workspace, "projects/sample/architecture.json")).exists()).toBe(false);
    await page.getByRole("button", { name: "Add UML to this project", exact: true }).click();
    await page.getByRole("region", { name: "UML editor", exact: true }).waitFor();
    expect(await page.getByRole("textbox", { name: "Message", exact: true }).isDisabled()).toBe(true);
    for (const [shape, name, x] of [["box", "Web app", "32"], ["class", "API service", "380"]]) {
      await page.getByText("+ Shape", { exact: true }).click();
      await page.getByRole("button", { name: `Add ${shape}`, exact: true }).click();
      await page.getByRole("textbox", { name: "Box name", exact: true }).fill(name ?? "");
      await page.getByRole("spinbutton", { name: "X", exact: true }).fill(x ?? "0");
      await page.getByRole("spinbutton", { name: "Y", exact: true }).fill("100");
    }
    await page.getByRole("textbox", { name: "Stereotype", exact: true }).fill("service");
    await page.getByRole("textbox", { name: "Attributes", exact: true }).fill("endpoint: URL");
    await page.getByRole("textbox", { name: "Operations", exact: true }).fill("saveNote()");
    const from = await page.getByLabel("Connect right of Web app", { exact: true }).boundingBox();
    const to = await page.getByLabel("Connect left of API service", { exact: true }).boundingBox();
    if (!from || !to) throw new Error("Connection handles are missing.");
    await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2); await page.mouse.down();
    await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 15 }); await page.mouse.up();
    await page.locator(".react-flow__edge").waitFor();
    const edgePoint = await page.locator(".react-flow__edge-path").evaluate(e => {
      if (!(e instanceof SVGPathElement)) throw new Error("Missing connector path.");
      const matrix = e.getScreenCTM();
      if (!matrix) throw new Error("The connector is not on screen.");
      const point = e.getPointAtLength(e.getTotalLength() / 2).matrixTransform(matrix); return { x: point.x, y: point.y };
    });
    await page.mouse.click(edgePoint.x, edgePoint.y);
    await page.getByLabel("Relationship", { exact: true }).selectOption("inheritance");
    await page.getByRole("textbox", { name: "End label", exact: true }).fill("0..*");
    const save = page.getByRole("button", { name: "Save diagram", exact: true });
    await save.click();
    await page.waitForFunction(() => document.querySelector(".uml-save-state")?.textContent === "Saved");
    let stored = await readArchitecture(workspace, "sample");
    expect(stored.state.diagrams[0]?.nodes).toHaveLength(2);
    expect(stored.state.diagrams[0]?.nodes.find(n => n.shape === "class")).toMatchObject({ stereotype: "service", attributes: "endpoint: URL", operations: "saveNote()" });
    expect(stored.state.diagrams[0]?.edges[0]?.endMarker).toBe("triangle");
    expect(stored.state.diagrams[0]?.edges[0]?.endLabel).toBe("0..*");
    expect(await page.getByRole("button", { name: "Undo", exact: true }).isEnabled()).toBe(true);
    await page.getByRole("button", { name: "Undo", exact: true }).click();
    expect(await page.getByRole("textbox", { name: "End label", exact: true }).inputValue()).toBe("");
    await page.getByRole("button", { name: "Redo", exact: true }).click();
    await page.getByRole("button", { name: "Hide UML", exact: true }).click();
    await page.getByRole("button", { name: "Show UML in this project", exact: true }).waitFor();
    stored = await readArchitecture(workspace, "sample");
    expect(stored.state.enabled).toBe(false); expect(stored.state.diagrams[0]?.nodes).toHaveLength(2);
    await page.getByRole("button", { name: "Show UML in this project", exact: true }).click();
    await page.reload({ waitUntil: "domcontentloaded" });
    await page.getByRole("tab", { name: "UML", exact: true }).click();
    await page.getByRole("button", { name: /System overview/ }).click();
    expect(await page.locator(".react-flow__node").count()).toBe(2); expect(await page.locator(".react-flow__edge").count()).toBe(1);
    await page.getByRole("group", { name: "API service", exact: true }).click();
    const resize = await page.locator(".react-flow__resize-control.handle.bottom.right").boundingBox();
    if (!resize) throw new Error("The resize control is missing.");
    await page.mouse.move(resize.x + resize.width / 2, resize.y + resize.height / 2); await page.mouse.down();
    await page.mouse.move(resize.x + resize.width / 2 + 48, resize.y + resize.height / 2 + 32, { steps: 10 }); await page.mouse.up();
    expect(Number(await page.getByRole("spinbutton", { name: "Width", exact: true }).inputValue())).toBeGreaterThan(220);
    const box = await page.getByRole("group", { name: "API service", exact: true }).boundingBox();
    if (!box) throw new Error("The box is missing.");
    await page.mouse.move(box.x + box.width / 2, box.y + 14); await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 + 32, box.y + 46, { steps: 10 }); await page.mouse.up();
    expect(Number(await page.getByRole("spinbutton", { name: "X", exact: true }).inputValue())).toBeGreaterThan(380);
    const geometry = await Promise.all(["X", "Y", "Width", "Height"].map(async name => Number(await page.getByRole("spinbutton", { name, exact: true }).inputValue())));
    await page.getByRole("button", { name: "Link UI design", exact: true }).click();
    await page.getByRole("tab", { name: "Comments", exact: true }).click();
    await page.getByRole("textbox", { name: "Comment on the selected item", exact: true }).fill("Keep the UI link.");
    await page.getByRole("button", { name: "Add diagram comment", exact: true }).click();
    await save.click(); await page.waitForFunction(() => document.querySelector(".uml-save-state")?.textContent === "Saved");
    expect((await readArchitecture(workspace, "sample")).state.diagrams[0]?.comments[0]?.text).toBe("Keep the UI link.");
    const resized = (await readArchitecture(workspace, "sample")).state.diagrams[0]?.nodes.find(n => n.name === "API service");
    expect(resized && [resized.position.x, resized.position.y, resized.size.width, resized.size.height]).toEqual(geometry);
    await page.reload({ waitUntil: "domcontentloaded" });
    await page.getByRole("tab", { name: "UML", exact: true }).click();
    await page.getByRole("button", { name: /System overview/ }).click();
    await page.getByRole("group", { name: "API service", exact: true }).click();
    expect(await Promise.all(["X", "Y", "Width", "Height"].map(async name => Number(await page.getByRole("spinbutton", { name, exact: true }).inputValue())))).toEqual(geometry);
    await page.getByRole("tab", { name: "UML", exact: true }).click();
    await page.getByRole("button", { name: /↗ home \/ index.html/ }).click();
    expect(await page.getByRole("region", { name: "UML editor", exact: true }).count()).toBe(0);
    expect(await page.getByRole("textbox", { name: "Message", exact: true }).isEnabled()).toBe(true);
    expect(await Bun.file(join(workspace, "projects/sample/designs/home/index.html")).text()).toBe(initialHtml);
    expect(turns).toBe(0); expect(errors).toEqual([]);
  } finally { await browser?.close(); app?.stop(); await rm(workspace, { recursive: true, force: true }); }
}, 45_000);
